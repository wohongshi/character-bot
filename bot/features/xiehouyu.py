MAX_HITS = 5


def _norm(text: str) -> str:
    return re.sub(r"[\s，。、！？：；「」『』（）()<>,.!?:;'\"…—\-～~]+", "", (text or "").strip())


def pick(pairs=None, rng=None) -> tuple:
    """随机一条（可注入 rng，索引夹在界内）。"""
    rng = rng or random.random
    pairs = pairs if pairs is not None else PAIRS
    return pairs[min(int(rng() * len(pairs)), len(pairs) - 1)]


def search(keyword: str, pairs=None, limit: int = MAX_HITS) -> list:
    """按关键词找：前半或后半命中都算（忽略标点空白）。"""
    kw = _norm(keyword)
    if not kw:
        return []
    pairs = pairs if pairs is not None else PAIRS
    return [(a, b) for a, b in pairs if kw in _norm(a) or kw in _norm(b)][:limit]


def format_one(pair) -> str:
    return f"{pair[0]}——{pair[1]}"


def register(api):
    async def cmd(ctx):
        raw = (ctx.arg_text or "").strip()
        if raw:
            hits = search(raw)
            if not hits:
                await ctx.reply(f"诶，可莉的小本本里没有跟「{raw[:12]}」有关的歇后语哦～\n"
                                f"要不来一条随机的？直接 .歇后语")
                return
            lines = "\n".join(f" · {format_one(h)}" for h in hits)
            head = f"🔎 跟「{raw[:12]}」有关的歇后语："
            await ctx.reply(f"{head}\n{lines}")
            return
        pair = pick()
        await ctx.reply(f"📖 {format_one(pair)}\n—— {random.choice(REMARKS)}")

    api.on_command("歇后语", cmd, aliases=("歇后", "俏皮话"), cooldown=3,
                   help=".歇后语 [关键词] —— 随机来一条，或按关键词找")
