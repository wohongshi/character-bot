"""昔莲 · 记忆列车：.列车

这趟车没有时刻表，报哪一站，取决于车上的人还记得什么。
"""
import random

NAME = "记忆列车"
DESCRIPTION = "听记忆列车报一次站：.列车"
VERSION = "1.0"
CHARACTERS = ("cyrene",)

STATIONS = [
    ("第一次下雪", "有人把围巾解开，分了一半给旁边不认识的人", "到站时谁也没下车。雪还在下。"),
    ("没说完的那句话", "一个人张了三次嘴，最后只是笑了笑", "那句话还留在座位上，没人认领。"),
    ("她回头的那一秒", "整节车厢都在看窗外，只有一个人在看她", "那一秒很长，长到足够记一辈子。"),
    ("所有人都还在的年夜", "孩子数着站名，数到一半就睡着了", "他手里还攥着一颗没舍得吃的糖。"),
    ("醒来之前的站台", "行李架上的箱子都没有写名字", "下车的人拿走了箱子，留下了梦。"),
    ("没有寄出的地址", "售票员报了一个谁也不认识的站名", "没有人问那是哪里。车还是停了。"),
]

CLOSERS = [
    "你可以不下车。这趟车不赶人。",
    "坐过站也没关系，我记得路。",
    "要是想回去，就在心里说一声，我会让车慢下来。",
]


def register(api):
    async def train(ctx):
        station, scene, tail = random.choice(STATIONS)
        await ctx.reply(
            f"🚃 下一站：{station}。\n"
            f"车厢里，{scene}。\n"
            f"{tail}\n"
            f"{random.choice(CLOSERS)}"
        )

    api.on_command("列车", train, help=".列车 —— 听记忆列车报一次站", cooldown=6)
