"""涂山红红 · 来客：.来客

今天来涂山的客人。一句画像，一句处理。
"""
import random

NAME = "来客"
DESCRIPTION = "看看今天谁来了涂山：.来客"
VERSION = "1.0"
CHARACTERS = ("honghong",)

VISITORS = [
    ("卖伞的", "伞骨断了两根，人倒是站得直，鞋上全是泥。", "伞留下。人进去喝口热的。"),
    ("找猫的", "抱着一只空篮子，说猫是三年前丢的。", "去后山找。找到算你的，找不到算它的。"),
    ("求续缘的", "一对小情人，手攥在一起，谁也不先开口。", "想清楚了再来。想不清楚，回去想。"),
    ("走错路的道士", "背着桃木剑，站在门口，进也不是退也不是。", "路在那边。别回头。"),
    ("收旧账的", "账本比人厚，笑得比账本还厚。", "账放下。人走。"),
    ("送信的", "一封信举过头顶，手一直在抖。", "信给我。你在门外等。"),
    ("学艺的小妖", "尾巴还没收干净，跪得倒是笔直。", "起来。涂山不收跪着的。"),
    ("算命的", "一进门就说我印堂发黑。", "你算得出自己今天走不出这道门吗。"),
]


def register(api):
    async def visitor(ctx):
        who, look, deal = random.choice(VISITORS)
        await ctx.reply(
            f"🏮 今日来客 · {who}\n"
            f"{look}\n"
            f"「{deal}」\n"
            "涂山不赶客。赶的是麻烦。"
        )

    api.on_command("来客", visitor, help=".来客 —— 今日涂山来客", cooldown=6)
