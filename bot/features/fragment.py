"""昔莲 · 记忆碎片：.碎片

完整的记忆太沉，她递过来的都是碎片。拼不拼得对，她也不保证。
"""
import random

NAME = "记忆碎片"
DESCRIPTION = "从地上捡三块记忆碎片：.碎片"
VERSION = "1.0"
CHARACTERS = ("cyrene",)

PIECES = [
    "一扇没有关严的门，门缝里有光",
    "有人在很远的地方喊了一个名字",
    "桌上一杯凉透的茶，杯沿有半个唇印",
    "雨停以后，屋檐还在滴水",
    "一只手的温度，很快就散了",
    "车站的钟慢了两分钟，没有人去调",
    "一本翻开的书，停在同一页很多年",
    "谁在楼下等，等到路灯亮起来",
    "口袋里的一张纸，字被洗得看不清",
    "镜子里的自己，比他先笑了一下",
    "一串钥匙，少了一把最重要的",
    "窗台上落了一层灰，有人用手指写了字",
    "厨房的灯亮着，锅里的水早就烧干了",
    "有人说过「明天见」，语气很平常",
    "一件借出去的外套，再也没还回来",
    "很轻的一声叹息，来自隔壁房间",
]

GUESSES = [
    "有个人在等另一个人，等了比说出口的更久",
    "发生过一次告别，但当时谁都没认出来",
    "有人在同一个地方，反复想起同一件事",
    "有句话一直没说，于是所有东西都替它留着位置",
    "那天其实很普通，只是后来再没有过那样的普通",
    "有人被好好地爱过，只是他当时不知道",
]


def register(api):
    async def fragment(ctx):
        pieces = random.sample(PIECES, 3)
        await ctx.reply(
            "🧩 三块碎片，我不知道是不是同一个人的：\n"
            + "\n".join(f"· {p}" for p in pieces)
            + f"\n拼起来大概是这样：{random.choice(GUESSES)}。\n"
            "也可能拼错了。碎片这东西，从来不肯好好排队。"
        )

    api.on_command("碎片", fragment, help=".碎片 —— 捡三块记忆碎片", cooldown=6)
