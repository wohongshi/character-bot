"""昔莲 · 写信：.写信 [收信人]

写给还没到的人，或者已经走远的人。信不必寄出去，写完就算送到了。
"""
import random

from _plugstore import safe_text

NAME = "写信"
DESCRIPTION = "替你把话写成一封信：.写信 [收信人]"
VERSION = "1.0"
CHARACTERS = ("cyrene",)

BODIES = [
    ["今天没有发生什么大事，所以我有空想你。",
     "如果那时候你已经忘了很多，没关系的，忘掉的和留下的都算数。",
     "我这边一切都好，只是偶尔会把别人的背影认成你。"],
    ["写这封信的时候，窗外正好有风，纸压了两次才没被吹走。",
     "我想说的其实只有一句：你不用变得更好，才值得被记得。",
     "剩下的，等见面再说吧，反正我们有的是时间。"],
    ["先说好，这封信不催你，也不问你在哪里。",
     "我只是想告诉你，今天有人提到了你的名字，我听见了，没有纠正他。",
     "如果你也刚好想起我，那就算我们见过一面了。"],
    ["近来睡得早了一些，梦却比从前长。",
     "梦里你还是原来的样子，站在门口，好像只是出去了一趟。",
     "醒来以后我没有难过，只是把窗帘拉开，让光进来。"],
    ["有件事我一直没学会：怎么好好地说再见。",
     "所以这封信里不写再见，写「下次」。",
     "下次你回来，我把窗台那盆花指给你看，它还活着。"],
    ["我把想说的话在心里排了队，排到一半就乱了。",
     "那就不排了。你只要知道，队伍里每一个人都在等你。",
     "慢慢来，我不催。我这儿最不缺的就是时间。"],
]

SIGNS = [
    "——昔莲，写于一个没什么特别的日子",
    "——昔莲。写完就折起来，不寄了。",
    "——昔莲，字有点歪，因为灯不太亮。",
    "——昔莲。若你收到，请当作我亲手递给你。",
]


def register(api):
    async def write(ctx):
        who = safe_text(ctx.arg_text, 16) or "十年后的你"
        body = random.choice(BODIES)
        await ctx.reply(
            f"✉ 给{who}：\n"
            + "\n".join(body)
            + "\n" + random.choice(SIGNS)
        )

    api.on_command("写信", write, help=".写信 [收信人] —— 写一封不必寄出的信", cooldown=6)
