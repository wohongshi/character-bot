"""茜特菈莉 · 酒馆轶事：.酒馆

八条从纳塔酒馆里听来的故事，一句钩子，一句收尾。
"""
import random

NAME = "酒馆轶事"
DESCRIPTION = "八条从酒馆听来的闲话：.酒馆"
VERSION = "1.0"
CHARACTERS = ("citlali",)

# (听说, 后来)
STORIES = [
    ("悬木人的酒馆里，有人用一袋燃素换了半壶酒，第二天那袋燃素自己走回了家。",
     "老板把这事记在账本上，账本从此每天自己翻一页。"),
    ("流泉众的姑娘说，她听见水底下有人唱歌，唱的是她小时候的名字。",
     "她蹲下去听，水面只映出她自己的脸，嘴没动。"),
    ("圣火竞技场外有个输光的人，把奖牌押给了卖烤肉的。",
     "后来他赢了十场回来赎，摊子上挂着的全是别人的奖牌。"),
    ("烟谜主的老祭师走前留了一炉不灭的烟，说等他回来再灭。",
     "烟烧了四十年，回来的是他孙子，说爷爷早就不在了。"),
    ("回声之子那边有个孩子，对着山谷喊一声，回的是两个声音。",
     "族里说另一个是他没出生的哥哥，孩子信了，天天去喊。"),
    ("沃陆之邦的集市上卖一种酒，喝了能梦见自己没选的那条路。",
     "摊主自己从不喝，说他已经梦见过太多次了。"),
    ("火山脚下有个守夜人，每晚数一遍星，少一颗就下山找人。",
     "他数了三十年，星一颗没少，人倒是找回来七个。"),
    ("夜神之国的渡口，船夫只收故事不收钱。",
     "有个商人讲了三天三夜，船夫听完说：这条不值一趟，你走回去吧。"),
]


def register(api):
    async def tavern(ctx):
        idx = random.randrange(len(STORIES))
        hook, tail = STORIES[idx]
        await ctx.reply(
            f"🍶 酒馆轶事 · 其{idx + 1}\n"
            f"听说：{hook}\n后来：{tail}\n"
            "——酒馆里的话，信三分，剩下七分下酒。"
        )

    api.on_command("酒馆", tavern, help=".酒馆 —— 听一条纳塔酒馆的闲话", cooldown=5)
