def register(api):
    async def borrow(ctx):
        topic = safe_text(ctx.arg_text, 20)
        if topic:
            hits = [s for s in SHELVES if any(k in topic for k in s[1])]
        else:
            hits = SHELVES
        fallback = ""
        if not hits:
            shelf = SHELVES[-1]
            fallback = f"没有找到和「{topic}」对得上的书架，我把它放进「无人认领」了。\n"
        else:
            shelf = random.choice(hits)
        name, _keys, pages = shelf
        await ctx.reply(
            f"📚 {fallback}「{name}」那一架，我替你抽了一本：\n"
            f"{random.choice(pages)}\n"
            f"——{random.choice(RETURNS)}"
        )

    api.on_command("借阅", borrow, help=".借阅 [主题] —— 从记忆图书馆借一页", cooldown=6)
