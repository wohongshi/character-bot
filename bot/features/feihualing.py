def raw_args(ctx) -> str:
    t = str(getattr(ctx, "text", "") or "").strip()
    body = t[1:].strip() if t[:1] in "./／" else t
    parts = body.split(None, 1)
    return parts[1] if len(parts) > 1 else ""


def lines_for(ch: str) -> list[tuple[str, str]]:
    return POEMS.get(ch, [])


def pick(ch: str, n: int = 3, rng=None) -> list[tuple[str, str]]:
    pool = list(lines_for(ch))
    rng = rng or random
    rng.shuffle(pool)
    return pool[:max(1, n)]


def register(api):
    async def cmd(ctx):
        raw = raw_args(ctx).strip()
        if not raw:
            keys = "".join(sorted(POEMS))
            await ctx.reply(f"用法：.飞花令 月 [几句]\n现在会的字：{keys}")
            return
        parts = raw.split()
        ch = parts[0]
        n = 3
        if len(parts) > 1 and parts[1].isdigit():
            n = max(1, min(6, int(parts[1])))
        if len(ch) != 1:
            await ctx.reply("飞花令一次只能指定一个字～例：.飞花令 月")
            return
        picks = pick(ch, n)
        if not picks:
            keys = "、".join(sorted(POEMS))
            await ctx.reply(f"「{ch}」我这儿还没收～现在会的：{keys}")
            return
        rows = [f"「{ln}」 —— {who}" for ln, who in picks]
        await ctx.reply(f"🌸 令字：{ch}\n" + "\n".join(rows))

    api.on_command("飞花令", cmd, aliases=("飞花", "poem"), cooldown=3,
                   help=".飞花令 <字> [句数] —— 报几句含这个字的诗")
