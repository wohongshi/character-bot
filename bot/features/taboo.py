def register(api):
    async def taboo(ctx):
        topic = safe_text(ctx.arg_text, 16)
        rule = None
        if topic:
            rule = next((r for r in RULES if any(k in topic for k in r[0])), None)
        if rule is None:
            rule = random.choice(RULES)
        _, title, body, tail = rule
        lines = [f"🚫 那边的规矩 · {title}"]
        if topic:
            lines.append(f"客官问的是「{topic}」。")
        else:
            lines.append("客官没点题，本堂主就随手翻一页。")
        lines.append(body)
        lines.append(tail)
        await ctx.reply("\n".join(lines))

    api.on_command("禁忌", taboo, help=".禁忌 [话题] —— 翻一条那边的规矩", cooldown=5)
