"""涂山红红 · 试爪：.试爪 [物品]

绝缘之爪空手试东西。抓得住、抓碎了、抓不住，都只说一句。
"""
import random

from _plugstore import safe_text

NAME = "试爪"
DESCRIPTION = "拿东西试她的绝缘之爪：.试爪 [物品]"
VERSION = "1.0"
CHARACTERS = ("honghong",)

# (关键词, 显示名, 结果, 她的话)
PRESETS = [
    (("剑", "刀", "枪", "兵器"), "剑",
     "剑刃抵在掌心，进不去半分。她两根手指一按，剑就哑了。", "「铁的。还行。下一个。」"),
    (("铃", "铃铛"), "铃铛",
     "铃没响。她捏在手里听了一会儿，才松开。铃身上留了四个指印。", "「响过一次。不是给你的。」"),
    (("符", "符纸", "咒"), "符纸",
     "符纸贴上掌心就烧了，连灰都没剩。她把手指在衣角上擦了擦。", "「道士的东西。下次别拿。」"),
    (("酒", "坛", "壶"), "酒坛",
     "坛口被她一手按住，封得比原来还严。酒一滴没洒出来。", "「留着。谁带来的谁拿走。」"),
    (("石", "石头", "砖"), "石头",
     "石头在手里碎成三块，落在脚边。碎渣从指缝里掉下去，她没拍。", "「脆。下次拿块硬的。」"),
    (("镜",), "铜镜",
     "镜子没碎。她把镜面转过来，对着你，自己退开半步。", "「照照自己。看清楚再说话。」"),
    (("梳",), "木梳",
     "梳齿一根没断。她捏了很久，指节都白了，才放下。", "「谁的。说。别让我问第二遍。」"),
    (("灯", "灯笼", "火把"), "灯笼",
     "火苗贴着掌心烧，烧不动她。她把手翻过来，火跟着翻。", "「提着。照路。别照我。」"),
]

LOOSE = [
    ("抓了一下，东西还在，上面留了四道印。她看了一眼就松开。", "「拿稳。别掉。」"),
    ("东西碎了。她看了一眼，没道歉，也没解释。", "「下次先说是什么。」"),
    ("没抓住。它自己滑了出去，撞在门框上，又弹回来。", "「滑。换个拿法。」"),
    ("她没伸手，只看了一眼。你看不出她在想什么。", "「没兴趣。收起来。」"),
]

HAND = ("她伸手，捏了一下你的手腕，然后松开。你的手不抖。", "「骨头没事。别硬撑。」")


def register(api):
    async def sword(ctx):
        raw = safe_text(ctx.arg_text, 16)
        if not raw:
            item = "你的手"
            result, line = HAND
        else:
            hit = next((p for p in PRESETS if any(k in raw for k in p[0])), None)
            if hit:
                _, item, result, line = hit
            else:
                item = raw
                result, line = random.choice(LOOSE)
        await ctx.reply(
            f"🐾 试爪 · {item}\n"
            "伸手。\n"
            f"{result}\n"
            f"{line}\n"
            "——下一个。"
        )

    api.on_command("试爪", sword, help=".试爪 [物品] —— 用绝缘之爪试一下", cooldown=5)
